-- ===========================================================================
-- Operational log: a finding, its reference, and the action to take
-- ===========================================================================
-- Everything else in this schema records what happened. None of it answers the
-- question an operator actually asks at 6pm on a Friday: "what is wrong right
-- now, where do I look, and what do I do about it?"
--
-- driver_verification_events has the trail for one driver. inventory_movements
-- has the trail for one dish. whatsapp_messages has the trail for one message.
-- Each is a fragment, in a different table, with a different shape, and none of
-- them carries a remedy. So diagnosing the WhatsApp 190 that started all of this
-- meant reading a Graph error and knowing what it implies.
--
-- One row is one finding with a stable reference the operator can quote in a
-- support ticket, a severity, what to look at, and what to do. `reference` is
-- stable across re-runs (it is a hash of kind + subject), so the same fault
-- reopening updates last_seen_at rather than piling up duplicates.
CREATE TABLE IF NOT EXISTS operation_logs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- Stable, quotable handle: e.g. LOG-WA-190-A1B2. Derived from kind + subject.
  reference TEXT NOT NULL UNIQUE,
  kind TEXT NOT NULL,                            -- whatsapp | delivery | menu | orders | credentials | music | release
  severity TEXT NOT NULL DEFAULT 'warning'
    CHECK (severity IN ('info','warning','error','critical')),
  -- What is wrong, in one line an operator can act on.
  title TEXT NOT NULL,
  -- The detail: Meta's own words, the row, the number. No interpretation.
  detail TEXT,
  -- What to look at to confirm it.
  evidence TEXT,                                 -- JSON: table, id, url, sql
  -- What to do about it, ordered. The whole point of the row.
  action TEXT NOT NULL,
  -- Deeper explanation, when the action needs justifying.
  context TEXT,
  -- Who or what should act: owner | manager | counter | kitchen | developer | meta
  owner TEXT NOT NULL DEFAULT 'manager',
  subject TEXT,                                  -- the row this is about, e.g. 'menu_item:1'
  status TEXT NOT NULL DEFAULT 'open'
    CHECK (status IN ('open','acknowledged','resolved','ignored')),
  first_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  occurrences INTEGER NOT NULL DEFAULT 1,
  resolved_at TIMESTAMPTZ,
  resolved_by TEXT,
  resolution_note TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_operation_logs_status
  ON operation_logs(status, severity, last_seen_at DESC);
CREATE INDEX IF NOT EXISTS idx_operation_logs_kind ON operation_logs(kind, last_seen_at DESC);

-- A finding's course of action as ordered, structured steps — who does what,
-- where, and how to confirm it worked — instead of one paragraph. `code` is the
-- stable id of the check that raised it (WA_TOKEN_UNVERIFIED), which is what a
-- runbook or a search is keyed on; the wording of the title is free to change.
ALTER TABLE operation_logs ADD COLUMN IF NOT EXISTS code TEXT;
ALTER TABLE operation_logs ADD COLUMN IF NOT EXISTS steps TEXT;        -- JSON [{do, where, owner, verify}]

-- ===========================================================================
-- Action log: one immutable row per action taken or attempted
-- ===========================================================================
-- operation_logs answers "what is wrong right now". It cannot answer "what was
-- done, by whom, did it work, and what has to happen next" — and that is the
-- question behind every support conversation: "I pressed publish and nothing
-- happened", "who changed the address", "did the token save".
--
-- One row is one action. It is written when the action finishes, whether it
-- worked or not, and never updated afterwards. Each row carries:
--   reference   quotable handle, ACT-<component>-<yymmdd>-<5 chars>
--   action      dotted code: orders.confirm, settings.update, auth.login
--   outcome     ok | rejected (a rule refused it) | denied (not allowed) |
--               failed (the system failed)
--   error_code  machine class of the failure: META_190, AUTH_REQUIRED, …
--   course      the course of action against this action, as ordered steps
-- Request bodies are stored redacted: credentials and setting values never
-- reach this table, and customer contact details are masked.
CREATE TABLE IF NOT EXISTS action_logs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference TEXT NOT NULL UNIQUE,
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  level TEXT NOT NULL DEFAULT 'info'
    CHECK (level IN ('info','notice','warning','error','critical')),
  component TEXT NOT NULL,                       -- auth | orders | menu | settings | whatsapp | …
  action TEXT NOT NULL,                          -- component.verb
  outcome TEXT NOT NULL DEFAULT 'ok'
    CHECK (outcome IN ('ok','rejected','denied','failed')),
  actor TEXT NOT NULL DEFAULT 'system',          -- staff email | customer | system
  actor_role TEXT,
  target TEXT,                                   -- order:KB-1042, menu_item:12, settings:a,b
  method TEXT,
  route TEXT,
  http_status INTEGER,
  duration_ms INTEGER,
  error_code TEXT,
  message TEXT NOT NULL,                         -- one line: what happened
  detail TEXT,                                   -- JSON: redacted request + response summary
  course TEXT NOT NULL,                          -- JSON {code, summary, steps:[{do, where, owner, verify}]}
  finding_reference TEXT,                        -- LOG-… this action relates to
  build TEXT,                                    -- v3.7.0+abc1234 that handled it
  request_id TEXT                                -- x-vercel-id: finds the function log line
);
CREATE INDEX IF NOT EXISTS idx_action_logs_time ON action_logs(occurred_at DESC);
CREATE INDEX IF NOT EXISTS idx_action_logs_level ON action_logs(level, occurred_at DESC);
CREATE INDEX IF NOT EXISTS idx_action_logs_action ON action_logs(component, action, occurred_at DESC);
CREATE INDEX IF NOT EXISTS idx_action_logs_outcome ON action_logs(outcome, occurred_at DESC);

-- The logs are read and written by the application only. On Supabase a table
-- in `public` is also served by the Data API to the `anon` role unless row
-- level security is on, so both log tables are closed to it here: RLS enabled,
-- no policies, which denies the API roles everything. The application connects
-- as the table owner, which RLS does not apply to.
--
-- Done once: the check avoids taking a table lock on every start. And it is
-- allowed to fail, for any reason: this file runs before the application will
-- answer anything, so a role without the right to alter the table, or a lock
-- that could not be taken, must cost a notice here (and a finding in the
-- operational log, which checks for it) rather than the site. A table left
-- open is tried again on the next start.
DO $$
DECLARE
  log_table text;
BEGIN
  FOREACH log_table IN ARRAY ARRAY['action_logs', 'operation_logs'] LOOP
    IF NOT (SELECT relrowsecurity FROM pg_class WHERE oid = to_regclass(log_table)) THEN
      EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', log_table);
    END IF;
  END LOOP;
EXCEPTION WHEN OTHERS THEN
  RAISE NOTICE 'Row level security was not enabled on the log tables: %', SQLERRM;
END $$;

