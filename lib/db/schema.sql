-- Customers -----------------------------------------------------------------
-- An account is optional: browsing, table QR ordering and the tracking link all
-- work signed out. These rows are what turn a one-off order into history —
-- "my orders", saved delivery details, and a counter lookup that does not
-- depend on the customer remembering an order code. Guests are rows with
-- guest = TRUE and no password; they are upgraded in place at sign-up.
CREATE TABLE IF NOT EXISTS customers (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,                 -- stored lowercased
  phone TEXT,
  password_hash TEXT,                         -- null until a guest registers
  address TEXT,
  suburb TEXT,
  postcode TEXT,
  marketing_opt_in BOOLEAN NOT NULL DEFAULT FALSE,
  guest BOOLEAN NOT NULL DEFAULT FALSE,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  last_order_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_customers_email ON customers(lower(email));

CREATE TABLE IF NOT EXISTS customer_activity (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id INTEGER NOT NULL REFERENCES customers(id) ON DELETE CASCADE,
  kind TEXT NOT NULL,                          -- signup | signin | order | orders_claimed | profile_updated
  detail TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_customer_activity ON customer_activity(customer_id, created_at DESC);

