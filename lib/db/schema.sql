-- Khan Baba platform schema (PostgreSQL / Supabase).
--
-- Applied automatically on the first query of every process (see lib/db/index.ts):
-- every statement is idempotent, so this file doubles as the migration script.
-- Types: identity integers for keys, timestamptz for instants, date for calendar
-- days, boolean for flags, double precision for quantities and integer cents for
-- money (never floats — the money math stays in whole cents).

CREATE TABLE IF NOT EXISTS settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS staff (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  role TEXT NOT NULL CHECK (role IN ('admin','manager','counter','kitchen','delivery')),
  password_hash TEXT NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

