  vehicle_type TEXT NOT NULL DEFAULT 'car',    -- car | motorbike | bicycle | van
  vehicle_rego TEXT,
  vehicle_make TEXT,
  licence_number TEXT,                        -- reference only; never a full scan
  licence_state TEXT,
  licence_expiry DATE,
  insurance_provider TEXT,
  insurance_expiry DATE,
  abn TEXT,
  right_to_work_country TEXT,
  police_check_ref TEXT,
  pay_id TEXT,
  address TEXT,
  suburb TEXT,
  postcode TEXT,
  base_lat DOUBLE PRECISION,
  base_lng DOUBLE PRECISION,
  commission_percent DOUBLE PRECISION NOT NULL DEFAULT 15,
  per_delivery_fee_cents INTEGER NOT NULL DEFAULT 300,
  max_radius_km DOUBLE PRECISION NOT NULL DEFAULT 15,
  current_lat DOUBLE PRECISION,
  current_lng DOUBLE PRECISION,
  last_seen_at TIMESTAMPTZ,
  terms_accepted_at TIMESTAMPTZ,
