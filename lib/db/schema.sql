-- Square POS bridge (deliberately detached) ---------------------------------
-- The main platform never reads these tables to run an order. They are the
-- synchronisation boundary: outbound pushes, inbound transactions and webhook
-- receipts all land here, so the whole module can be removed without touching
-- the order state machine.
CREATE TABLE IF NOT EXISTS square_sync_records (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  direction TEXT NOT NULL CHECK (direction IN ('outbound','inbound','webhook','test')),
  entity TEXT NOT NULL,
  entity_ref TEXT,
  external_id TEXT,
  status TEXT NOT NULL CHECK (status IN ('ok','pending','skipped','error')),
  message TEXT,
  payload TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_square_sync ON square_sync_records(created_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS square_transactions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  external_id TEXT NOT NULL UNIQUE,
  kind TEXT NOT NULL,                          -- payment | order | refund | payout
  source TEXT NOT NULL,                        -- square | local
  order_code TEXT,
  square_order_id TEXT,
  location_id TEXT,
  amount_cents INTEGER NOT NULL DEFAULT 0,
  currency TEXT NOT NULL DEFAULT 'AUD',
  status TEXT,
  occurred_at TIMESTAMPTZ,
  raw TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_square_transactions ON square_transactions(occurred_at DESC);
