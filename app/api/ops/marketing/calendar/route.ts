import { NextResponse } from "next/server";
import { getDb } from "@/lib/db";
import { getApiSession } from "@/lib/auth/api";
import { getSettings } from "@/lib/settings";
import { calendarMarkdown, contentCalendar } from "@/lib/marketing/calendar";
import { publicBaseUrl } from "@/lib/url";

export const dynamic = "force-dynamic";
export const maxDuration = 30;

/**
 * The 7-day content calendar, as data or as Markdown.
 *
 *   GET /api/ops/marketing/calendar            → JSON for the portal
 *   GET /api/ops/marketing/calendar?format=md  → the same Markdown that
 *                                                `npm run marketing:calendar`
 *                                                writes to marketing/
 *
 * Read-only by design. The file on disk is generated by the CLI; this endpoint
 * exists so the owner can read the week on a phone without a checkout, and so
 * the portal can show it without duplicating the generator.
 */
export async function GET(request: Request) {
  const session = await getApiSession(["admin", "manager"]);
  if (!session) {
    return NextResponse.json({ error: "Not authorised" }, { status: 401 });
  }

  const url = new URL(request.url);
  const startParam = url.searchParams.get("start");
  let start: Date | undefined;
  if (startParam) {
    if (!/^\d{4}-\d{2}-\d{2}$/.test(startParam)) {
      return NextResponse.json({ error: "start must be YYYY-MM-DD" }, { status: 400 });
    }
    start = new Date(`${startParam}T00:00:00Z`);
  }

  const db = await getDb();
  const calendar = await contentCalendar(db, publicBaseUrl(), start);

  if (url.searchParams.get("format") === "md") {
    const settings = await getSettings();
    return new NextResponse(calendarMarkdown(calendar, settings), {
      headers: { "content-type": "text/markdown; charset=utf-8", "cache-control": "no-store" },
    });
  }

  return NextResponse.json({ ok: true, calendar });
}
